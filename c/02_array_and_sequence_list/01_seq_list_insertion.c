#include <stdio.h>

/**
 * 💡【知识点】顺序表/数组 —— 元素插入 (Array Insertion)
 * -----------------------------------------------------------------------------
 * 📌【概念与本质】
 *   顺序表基于物理连续内存。插入新元素时，为了维护内存连续性并为新值腾出空间，
 *   目标位置及其后续的所有元素都必须向后位移一位。
 * 
 * 📌【双变量状态模型】
 *   • 容量 (capacity) : 数组分配的最大物理空间上限。
 *   • 长度 (n)        : 当前数组中实际存有的有效元素个数 (n <= capacity)。
 * 
 * 📌【架构与模块分工】
 *   1. insert()     : 核心操作 —— 边界防御 -> 【从后往前】位移腾位 -> 写入新值 -> 长度+1。
 *   2. printArray() : 辅助工具 —— 输出数组当前状态与有效长度。
 *   3. main()       : 驱动入口 —— 状态追踪与常规/边界用例测试。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 在数组指定索引 pos 处插入新值 value
 * 
 * 🔍【核心逻辑深度剖析】：
 *   1. 边界检查为什么是 [0, n]？
 *      - pos = 0 表示头插（插入最前，需移动全部 n 个元素）。
 *      - pos = n 表示尾插（直接追加在末尾，无需移动任何元素）。
 *   2. 为什么位移必须【从后往前】？（核心易错点！）
 *      - 若从前往后：arr[pos+1] = arr[pos] 会直接覆盖掉原 arr[pos+1] 的值，导致后续数据连锁丢失！
 *      - 从后往前：从空闲的 arr[n] 开始倒序把前一个元素搬过来 (arr[i] = arr[i-1])，安全腾出 arr[pos]。
 *   3. 复杂度深度剖析：
 *      - 最好情况：尾插 (pos = n)，无需移动元素 -> 时间复杂度 O(1)。
 *      - 最坏情况：头插 (pos = 0)，需移动全部 n 个元素 -> 时间复杂度 O(N)。
 *      - 平均情况：平均移动 n / 2 个元素 -> 时间复杂度 O(N)。
 *      - 空间复杂度：原地操作，空间复杂度 O(1)。
 */
int insert(int arr[], int n, int pos, int value, int capacity) {
    // 步骤 1：容量溢出检查
    if (n >= capacity) {
        printf("【插入失败】数组已满（容量上限 %d），无法插入！\n", capacity);
        return -1;
    }

    // 步骤 2：插入索引合法性校验 (必须位于 [0, n] 闭区间)
    if (pos < 0 || pos > n) {
        printf("【插入失败】索引 %d 不合法！有效插入范围为 [0, %d]\n", pos, n);
        return -1;
    }

    // 步骤 3：核心后移 —— 从索引 n 倒序扫描至 pos + 1，将前一位数据后搬
    for (int i = n; i > pos; i--) {
        arr[i] = arr[i - 1];
    }
    
    // 步骤 4：在腾出的 pos 空位写入新元素
    arr[pos] = value;

    // 步骤 5：返回更新后的元素有效个数 (n + 1)
    return n + 1;
}

// ==================== 2. 辅助工具函数 ====================

void printArray(const char* tag, int arr[], int n) {
    printf("%s [当前有效长度: %d]: [ ", tag, n);
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]);
    }
    printf("]\n");
}

// ==================== 3. 测试与验证入口 ====================

int main(void) {
    int capacity = 10;
    int arr[10] = {10, 20, 30, 40};
    int n = 4; // 初始有效长度为 4

    printf("================ 顺序表插入操作测试 ================\n");
    printArray("初始状态", arr, n);

    // 测试 1：常规插入 —— 在索引 2 处插入 25 (在 20 和 30 之间)
    printf("\n--> 执行插入：在索引 2 处插入数值 25\n");
    int new_n = insert(arr, n, 2, 25, capacity);
    if (new_n != -1) {
        n = new_n; // 插入成功，同步更新有效长度 n
        printArray("插入成功", arr, n);
    }

    // 测试 2：异常边界测试 —— 插入非法超界索引 100
    printf("\n--> 边界测试：尝试在非法索引 100 处插入\n");
    insert(arr, n, 100, 999, capacity);

    return 0;
}