// ==================== 0. 标准库头文件引入与作用解析 ====================
#include <stdio.h>    // 标准输入输出库：提供 printf(), puts() 等控制台格式化输出函数
#include <stdbool.h>  // C99 标准布尔库：提供 bool, true, false 逻辑判定类型支持

/**
 * =============================================================================
 * 💡【知识点】顺序表/数组 —— 线性查找 (Linear Search)
 * =============================================================================
 * 
 * 📌【1. 什么是线性查找？】
 *   线性查找（又称顺序查找）是最基础、最通用的查找算法。
 *   - 核心逻辑：从数据结构的第一个元素开始，顺次遍历每个元素，并与目标值 (target) 逐一进行比对。
 *   - 终止条件：
 *     ① 匹配成功：立即返回该元素的下标（提前终止）。
 *     ② 扫描到底仍未找到：返回特殊标记值 `-1`（表示未命中）。
 * 
 * 📌【2. 线性查找过程图解】
 * 
 *   查找 target = 48
 *   
 *   下标:    [ 0 ]   [ 1 ]   [ 2 ]   [ 3 ]   [ 4 ]
 *   数据:    | 15  | | 32  | | 48  | | 64  | | 80  |
 *             ▲       ▲       ▲
 *   步骤:    ①比对!=  ②比对!=  ③比对== (命中！立即返回下标 2)
 * 
 * 📌【3. 深度思考与高频 Q&A】
 * 
 *   ❓ Q1: 既然二分查找只要 O(log N)，为什么我们还需要 O(N) 的线性查找？
 *      👉 解答：
 *         - 前提条件不同：二分查找**强制要求数组必须预先有序**！如果数组无序，排序本身需要 O(N log N) 代价。
 *         - 适用容器广泛：线性查找对数据是否有序没有任何要求，并且适用于单链表、流式数据等无法随机访问的结构。
 * 
 *   ❓ Q2: 为什么未找到时通常返回 `-1`？
 *      👉 解答：因为 C 语言中合法数组下标是从 `0` 到 `N-1` 的非负整数，`-1` 作为哨兵值 (Sentinel Value)
 *         可以毫无歧义地表示“无效下标/未找到”。
 * =============================================================================
 */

// ==================== 1. 查找算法实现 ====================

/**
 * @brief 在数组中顺序线性查找目标元素
 * 
 * @param arr    待查找的数组指针
 * @param size   数组有效元素个数
 * @param target 目标查找值
 * @return int 找到时返回对应下标 (0 ~ size-1)，未找到返回 -1
 * 
 * @note 时间复杂度: 最好 O(1)（首个元素即命中），最坏 O(N)（末尾命中或不存在），平均 O(N)
 * @note 空间复杂度: O(1) —— 原地遍历，无需额外辅助空间
 */
int linear_search(const int arr[], int size, int target) {
    if (arr == NULL || size <= 0) {
        return -1;
    }

    // 【步骤 1】从头到尾依次比对
    for (int i = 0; i < size; i++) {
        if (arr[i] == target) {
            // 【步骤 2】命中目标，直接返回当前下标（短路返回，省去后续无谓比对）
            return i;
        }
    }

    // 【步骤 3】整表扫描完毕，确认不存在目标值
    return -1;
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int arr[] = {15, 32, 48, 64, 80};
    int size = sizeof(arr) / sizeof(arr[0]);

    printf("==================== 线性查找算法验证 ====================\n");
    printf("待查数组: [ 15, 32, 48, 64, 80 ] (共 %d 个元素)\n\n", size);

    // 测试用例 1: 查找存在的元素
    int target1 = 48;
    int index1 = linear_search(arr, size, target1);
    if (index1 != -1) {
        printf("✅ [测试 1] 查找目标 %d 成功！所在下标为: %d\n", target1, index1);
    } else {
        printf("❌ [测试 1] 未找到目标 %d\n", target1);
    }

    // 测试用例 2: 查找不存在的元素
    int target2 = 99;
    int index2 = linear_search(arr, size, target2);
    if (index2 != -1) {
        printf("✅ [测试 2] 查找目标 %d 成功！所在下标为: %d\n", target2, index2);
    } else {
        printf("❌ [测试 2] 未找到目标 %d (返回值: %d)\n", target2, index2);
    }

    return 0;
}
