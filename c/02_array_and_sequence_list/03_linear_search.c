#include <stdio.h>

/**
 * 💡【知识点】顺序表/数组 —— 线性查找 / 顺序查找 (Linear Search)
 * -----------------------------------------------------------------------------
 * 📌【概念与本质】
 *   线性查找是针对无序数据集合最通用、最质朴的查找方式。
 *   算法从数组首元素出发，沿物理顺序逐一比对目标值（Target）。
 * 
 * 📌【设计思想与返回值约定】
 *   • 早退机制 (Early Return)：一旦比对命中立即返回索引，避免无意义的后续遍历（最好情况 O(1)）。
 *   • 哨兵返回值 (-1)：数组合法索引为 0 ~ n-1，因此用负数 -1 作为“未查找到”的标准状态码。
 *   • 进阶思考：若数组已提前升序/降序排好，应选用【二分查找 (Binary Search)】将复杂度降至 O(log N)。
 * 
 * 📌【架构与模块分工】
 *   1. search() : 核心查找算法 —— 循环比对 -> 命中早退 -> 未命中返回 -1。
 *   2. main()   : 驱动入口 —— 构造“命中”与“未命中”两组经典用例验证。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 在整型数组中顺序查找指定的目标值
 * 
 * 🔍【核心逻辑深度剖析】：
 *   • 遍历过程：扫描区间 [0, n - 1]。
 *   • 比对分支：
 *     - 若 arr[i] == target：命中目标，立即 return i，结束函数调用。
 *     - 若整个循环结束仍未触发 return：说明数组不含该元素，返回 -1。
 *   • 复杂度深度剖析：
 *     - 最好情况：目标恰好位于首位 arr[0] -> 比较 1 次，时间复杂度 O(1)。
 *     - 最坏情况：目标位于末尾 arr[n-1] 或根本不存在 -> 比较 n 次，时间复杂度 O(N)。
 *     - 平均情况：平均比较 (n + 1) / 2 次 -> 时间复杂度 O(N)。
 *     - 空间复杂度: 原地扫描，空间复杂度 O(1)。
 */
int search(int arr[], int n, int target) {
    for (int i = 0; i < n; i++) {
        if (arr[i] == target) {
            return i; // 命中目标，立即早退
        }
    }
    return -1; // 查遍全表未命中，返回约定值 -1
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int arr[] = {43, 17, 89, 25, 61};
    int n = sizeof(arr) / sizeof(arr[0]);

    printf("================ 线性查找算法测试 ================\n");
    printf("待查数组: [ 43, 17, 89, 25, 61 ]\n\n");

    // 用例 1：查找存在的元素 (89)
    int target1 = 89;
    int idx1 = search(arr, n, target1);
    if (idx1 != -1) {
        printf("【查找成功】目标 %d 位于索引 [%d]\n", target1, idx1);
    } else {
        printf("【查找失败】数组中未找到目标 %d\n", target1);
    }

    // 用例 2：查找不存在的元素 (999)
    int target2 = 999;
    int idx2 = search(arr, n, target2);
    if (idx2 != -1) {
        printf("【查找成功】目标 %d 位于索引 [%d]\n", target2, idx2);
    } else {
        printf("【查找失败】数组中未找到目标 %d\n", target2);
    }

    return 0;
}