#include <stdio.h>

/**
 * 💡【知识点】顺序表/数组 —— 元素删除 (Array Deletion)
 * -----------------------------------------------------------------------------
 * 📌【概念与本质】
 *   从连续存储空间中移除指定位置的元素。删除后留下的“空洞”必须通过
 *   将后续所有元素向前位移一位来填补，以保证物理内存的无缝连续性。
 * 
 * 📌【架构与模块分工】
 *   1. delete()     : 核心操作 —— 空表校验 -> 索引检查 -> 【从前往后】前移覆盖 -> 长度-1。
 *   2. printArray() : 辅助工具 —— 输出数组当前状态与有效长度。
 *   3. main()       : 驱动入口 —— 状态追踪与常规/边界用例测试。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 删除数组中指定索引 pos 处的元素
 * 
 * 🔍【核心逻辑深度剖析】：
 *   1. 边界检查为什么是 [0, n - 1]？
 *      - 区别于插入操作（插入允许 pos = n 尾插），删除操作必须针对已有的实际元素，因此最大索引只能是 n - 1。
 *      - 若 n <= 0（空表），则无任何元素可删。
 *   2. 为什么位移必须【从前往后】覆盖？（核心易错点！）
 *      - 从 pos 开始，每次将后一个元素拉到前一个位置 (arr[i] = arr[i+1])，逐步向前覆盖。
 *      - 若从后往前移，会导致前面的数据被错误覆盖！
 *   3. 内存层面的删除本质：
 *      - 计算机内存中的数据不会真正“物理消失”，而是通过前移覆盖和有效长度 (n-1) 的缩减，使被删数据逻辑失效。
 *   4. 复杂度深度剖析：
 *      - 最好情况：尾删 (pos = n - 1)，无需移动任何元素，直接长度 - 1 -> 时间复杂度 O(1)。
 *      - 最坏情况：头删 (pos = 0)，需前移后续全部 n - 1 个元素 -> 时间复杂度 O(N)。
 *      - 平均情况：平均移动 (n - 1) / 2 个元素 -> 时间复杂度 O(N)。
 *      - 空间复杂度：原地操作，空间复杂度 O(1)。
 */
int delete(int arr[], int n, int pos) {
    // 步骤 1：空表检查（防止数组下溢）
    if (n <= 0) {
        printf("【删除失败】数组为空，无数据可删除！\n");
        return -1;
    }

    // 步骤 2：删除索引合法性校验 (必须在 [0, n - 1] 闭区间)
    if (pos < 0 || pos >= n) {
        printf("【删除失败】索引 %d 不合法！有效删除范围为 [0, %d]\n", pos, n - 1);
        return -1;
    }

    // 步骤 3：核心前移 —— 从 pos 顺序扫描至 n - 2，将后一位数据左移覆盖
    for (int i = pos; i < n - 1; i++) {
        arr[i] = arr[i + 1];
    }

    // 步骤 4：返回删除后的新有效长度 (n - 1)
    return n - 1;
}

// ==================== 2. 辅助工具函数 ====================

void printArray(const char* tag, int arr[], int n) {
    printf("%s [当前有效长度: %d]: [ ", tag, n);
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]);
    }
    printf("]\n");
}

// ==================== 3. 测试与验证入口 ====================

int main(void) {
    int arr[10] = {10, 20, 30, 40, 50};
    int n = 5; // 初始有效长度为 5

    printf("================ 顺序表删除操作测试 ================\n");
    printArray("初始状态", arr, n);

    // 测试 1：常规删除 —— 删除索引 2 处的元素 (数值 30)
    printf("\n--> 执行删除：删除索引 2 处的元素 (值 30)\n");
    int new_n = delete(arr, n, 2);
    if (new_n != -1) {
        n = new_n; // 删除成功，同步更新有效长度 n
        printArray("删除成功", arr, n);
    }

    // 测试 2：异常边界测试 —— 尝试删除超出上限的索引 10
    printf("\n--> 边界测试：尝试删除不存在的索引 10\n");
    delete(arr, n, 10);

    return 0;
}