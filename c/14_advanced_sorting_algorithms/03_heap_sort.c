#include <stdio.h>    // 标准输入输出库：提供 printf(), puts() 等控制台格式化输出函数

/**
 * =============================================================================
 * 💡【知识点】高级排序算法 —— 堆排序 (Heap Sort / 原地堆化与极值提取)
 * =============================================================================
 * 
 * 📌【1. 什么是堆排序？】
 *   堆排序利用了「最大堆」堆顶永远是全局最大值的特性，实现了真正的「原地 $O(1)$ 辅助空间」排序！
 *   - 阶段 1（原地建堆）：从最后一个非叶子节点 `(n/2 - 1)` 开始向前遍历执行下沉调整 (Sift Down)，
 *     在线性时间 $O(N)$ 内将任意无序数组改造为合法的最大堆。
 *   - 阶段 2（极值提取与交换）：
 *     ① 将堆顶元素 `arr[0]`（当前最大值）与当前堆末尾元素 `arr[i]` 交换（最大值归位到数组后方！）。
 *     ② 将堆的有效计算范围减 1。
 *     ③ 对新的堆顶 `arr[0]` 重新执行下沉调整以恢复最大堆性质。
 *     ④ 重复上述步骤，直到堆大小缩减为 1，整个数组便原地变为升序有序！
 * 
 * 📌【2. 堆排序原地排序过程图解】
 * 
 *   [ 阶段 1: 建好最大堆 ]  [13, 11, 12, 5, 6, 7]  (堆顶 13 是最大值)
 *   
 *   [ 阶段 2: 交换与下沉 ]
 *     ① 交换 13 与末尾 7  -> [ 7, 11, 12, 5, 6 | (13已归位) ]
 *     ② 对 7 下沉调整      -> [ 12, 11, 7, 5, 6 | (13) ]
 *     ③ 交换 12 与末尾 6  -> [ 6, 11, 7, 5 | (12), (13) ]
 *     ④ 循环往复... 最终数组自然呈现 [5, 6, 7, 11, 12, 13] 升序！
 * 
 * 📌【3. 深度思考与高频 Q&A】
 * 
 *   ❓ Q1: 堆排序与快速排序、归并排序相比有什么优势？
 *      👉 对比：
 *         - 快排：平均最快，但最坏情况下可能退化为 $O(N^2)$。
 *         - 归并：任何情况下都是稳定 $O(N \log N)$，但需要额外 $O(N)$ 辅助空间。
 *         - **堆排**：任何情况下时间复杂度都是严格的 **$O(N \log N)$**，且额外空间仅需 **$O(1)$**！
 * =============================================================================
 */

// ==================== 1. 核心算法实现 ====================

static void swap(int *a, int *b) {
    int t = *a; 
    *a = *b; 
    *b = t;
}

/**
 * @brief 核心下沉调整函数 (Heapify)
 * 
 * @param arr 数组指针
 * @param n   当前堆的有效元素边界
 * @param i   待下沉的节点下标
 * 
 * @note 时间复杂度: O(log N)
 */
static void heapify(int arr[], int n, int i) {
    int largest = i;       // 初始化最大值下标为父节点
    int left = 2 * i + 1;  // 左孩子下标
    int right = 2 * i + 2; // 右孩子下标

    // 检查左孩子是否更大
    if (left < n && arr[left] > arr[largest]) {
        largest = left;
    }

    // 检查右孩子是否更大
    if (right < n && arr[right] > arr[largest]) {
        largest = right;
    }

    // 若最大值不是父节点自身，交换并递归向下维护
    if (largest != i) {
        swap(&arr[i], &arr[largest]);
        heapify(arr, n, largest); // 递归下沉
    }
}

/**
 * @brief 堆排序主入口
 * 
 * @param arr 待排序数组
 * @param n   数组元素总数
 * 
 * @note 时间复杂度: 严格 O(N log N)
 * @note 空间复杂度: O(1) —— 纯原地操作，无需辅助数组
 */
void heap_sort(int arr[], int n) {
    // 【阶段 1】原地构建最大堆 (从最后一个非叶子节点 n/2 - 1 倒序下沉到底)
    for (int i = n / 2 - 1; i >= 0; i--) {
        heapify(arr, n, i);
    }

    // 【阶段 2】逐个提取最大堆顶，交换至数组末端并缩小堆范围
    for (int i = n - 1; i > 0; i--) {
        // 将当前最大值（堆顶 arr[0]）与当前未排序区间末尾 arr[i] 交换
        swap(&arr[0], &arr[i]);

        // 对剩余的 i 个元素重新对堆顶执行下沉，维持最大堆性质
        heapify(arr, i, 0);
    }
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int arr[] = {12, 11, 13, 5, 6, 7};
    int n = sizeof(arr) / sizeof(arr[0]);

    printf("==================== 堆排序 (Heap Sort) 验证 ====================\n\n");
    printf("待排数组: ");
    for (int i = 0; i < n; i++) printf("%d ", arr[i]);
    printf("\n");

    heap_sort(arr, n);

    printf("堆排结果: ");
    for (int i = 0; i < n; i++) printf("%d ", arr[i]);
    printf(" (升序有序)\n");

    return 0;
}
