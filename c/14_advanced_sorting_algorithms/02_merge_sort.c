#include <stdio.h>
#include <stdlib.h>

/**
 * =============================================================================
 * 💡【知识点】高级排序算法 —— 归并排序 (Merge Sort / 分治与双路归并)
 * =============================================================================
 * 
 * 📌【1. 什么是归并排序？】
 *   由计算机之父冯·诺依曼 (John von Neumann) 提出的经典「分治 (Divide and Conquer)」算法。
 *   - 分割 (Divide)  ：将数组从正中间对半切开，递归拆分直到每个子区间只剩 1 个元素（1 个元素天然有序）。
 *   - 合并 (Conquer) ：利用双指针技术，将两个已经各自有序的子序列合并为一个更大的有序序列。
 * 
 * 📌【2. 归并排序拆解与合并过程图解】
 * 
 *                 [ 38, 27, 43, 3, 9, 82, 10 ]
 *                     /                  \
 *            [ 38, 27, 43, 3 ]      [ 9, 82, 10 ]        <--- 递归向下拆解
 *              /          \            /       \
 *          [38, 27]     [43, 3]     [9, 82]    [10]
 *          /      \     /     \     /     \     |
 *        [38]   [27]  [43]   [3]   [9]   [82]  [10]
 *   -----------------------------------------------------
 *        [ 27, 38 ]   [ 3, 43 ]     [ 9, 82 ]  [10]      <--- 双指针向上合并
 *            \             /             \       /
 *          [ 3, 27, 38, 43 ]           [ 9, 10, 82 ]
 *                 \                         /
 *                [ 3, 9, 10, 27, 38, 43, 82 ]
 * 
 * 📌【3. 深度思考与高频 Q&A】
 * 
 *   ❓ Q1: 归并排序为什么是「稳定排序 (Stable Sort)」？
 *      👉 解答：在合并时，只要当 `L[i] <= R[j]` 时优先取左边的元素放入原数组，
 *         就能严格保证相同数值的相对前后位置在排序前后绝不发生颠倒。
 * 
 *   ❓ Q2: 归并排序的致命缺点是什么？
 *      👉 解答：需要申请大小为 $O(N)$ 的额外辅助数组空间用于暂存左右子序列，内存开销比快排和堆排更大。
 * =============================================================================
 */

// ==================== 1. 核心算法实现 ====================

/**
 * @brief 双路有序合并核心函数
 * 
 * @param arr 原始数组
 * @param l   左子序列起点
 * @param m   左子序列终点 (右子序列起点为 m + 1)
 * @param r   右子序列终点
 * 
 * @note 时间复杂度: O(N) —— 双指针线性归并
 * @note 空间复杂度: O(N) —— 动态申请临时辅助数组
 */
static void merge(int arr[], int l, int m, int r) {
    int n1 = m - l + 1; // 左子序列长度
    int n2 = r - m;     // 右子序列长度

    // 【步骤 1】申请临时数组暂存左右两半数据
    int *L = (int *)malloc((size_t)n1 * sizeof(int));
    int *R = (int *)malloc((size_t)n2 * sizeof(int));

    for (int i = 0; i < n1; i++) L[i] = arr[l + i];
    for (int j = 0; j < n2; j++) R[j] = arr[m + 1 + j];

    // 【步骤 2】双指针比对较小值，依次写回原数组 arr
    int i = 0; // L 的游标
    int j = 0; // R 的游标
    int k = l; // arr 的写回游标

    while (i < n1 && j < n2) {
        // ⚠️ `<=` 严格维持稳定性
        if (L[i] <= R[j]) {
            arr[k++] = L[i++];
        } else {
            arr[k++] = R[j++];
        }
    }

    // 【步骤 3】将剩余未处理完的元素直接全部拷贝回原数组
    while (i < n1) arr[k++] = L[i++];
    while (j < n2) arr[k++] = R[j++];

    // 【步骤 4】释放临时辅助空间
    free(L);
    free(R);
}

/**
 * @brief 归并排序递归切分函数
 */
void merge_sort(int arr[], int l, int r) {
    if (l < r) {
        int m = l + (r - l) / 2; // 防溢出求中点

        // 递归拆分左半边
        merge_sort(arr, l, m);
        // 递归拆分右半边
        merge_sort(arr, m + 1, r);
        // 合并两个有序半区
        merge(arr, l, m, r);
    }
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int arr[] = {38, 27, 43, 3, 9, 82, 10};
    int n = sizeof(arr) / sizeof(arr[0]);

    printf("==================== 归并排序 (Merge Sort) 验证 ====================\n\n");
    printf("待排数组: ");
    for (int i = 0; i < n; i++) printf("%d ", arr[i]);
    printf("\n");

    merge_sort(arr, 0, n - 1);

    printf("归并结果: ");
    for (int i = 0; i < n; i++) printf("%d ", arr[i]);
    printf(" (升序有序)\n");

    return 0;
}
