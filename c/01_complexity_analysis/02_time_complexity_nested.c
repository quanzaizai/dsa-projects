#include <stdio.h>

/**
 * 【知识点】时间复杂度 O(N^2) —— 平方阶时间复杂度
 * -----------------------------------------------------------------------------
 * 1. 核心思想：双层嵌套循环，外层执行 N 次，内层也执行 N 次，总操作约为 N * N。
 * 2. 常见场景：矩阵/网格遍历、冒泡排序、选择排序等经典算法。
 * -----------------------------------------------------------------------------
 */

// 双层循环打印 N x N 乘法表/矩阵 -> 时间复杂度 O(N^2)
void printMatrix(int n) {
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= n; j++) {
            printf("%4d", i * j);
        }
        printf("\n");
    }
}

int main(void) {
    int n = 5;
    printf("--- %d x %d 乘法矩阵 (O(N^2)) ---\n", n, n);
    printMatrix(n);
    return 0;
}
