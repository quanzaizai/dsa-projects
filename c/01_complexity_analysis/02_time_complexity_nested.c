#include <stdio.h>

/**
 * =============================================================================
 * 💡【知识点】时间复杂度 (Time Complexity) —— 平方阶 O(N^2)
 * =============================================================================
 * 
 * 📌【1. 什么是平方阶 O(N^2)？】
 *   当代码中出现「双层嵌套循环」，且内层循环的执行次数与外层紧密相关时，整体计算量往往达到 N * N = N^2 数量级。
 *   - 增长特征：数据规模每扩大 10 倍，计算耗时激增 100 倍！
 *   - 常见场景：二维矩阵遍历、冒泡排序、选择排序、两两配对校验。
 * 
 * 📌【2. 嵌套循环的执行模型图解】
 * 
 *   外层 i=1  ->  内层执行 N 次 (j = 1, 2, ..., N)  ========> N 次
 *   外层 i=2  ->  内层执行 N 次 (j = 1, 2, ..., N)  ========> N 次
 *   外层 i=3  ->  内层执行 N 次 (j = 1, 2, ..., N)  ========> N 次
 *   ...
 *   外层 i=N  ->  内层执行 N 次 (j = 1, 2, ..., N)  ========> N 次
 *   --------------------------------------------------------------
 *   【总基本操作次数】 = N + N + N + ... (共 N 个 N) = N * N = N^2 次！
 * 
 * 📌【3. 深度思考与高频 Q&A】
 * 
 *   ❓ Q1: 如果内层循环不是跑满 N 次，而是 `for(int j=i; j<=n; j++)`，复杂度还是 O(N^2) 吗？
 *      👉 解答（高斯求和公式）：
 *         - 执行次数 = N + (N-1) + (N-2) + ... + 2 + 1 = N * (N + 1) / 2 = 0.5 * N^2 + 0.5 * N。
 *         - 按照大 O 渐进记法，去掉最高阶的系数 0.5 并忽略低阶项 0.5N，结果依然是 O(N^2)！
 * 
 *   ❓ Q2: 两个独立的单层循环 `for(..N..)` 和 `for(..N..)` 是 O(N^2) 吗？
 *      👉 解答：
 *         - 独立（并列）执行是相加关系：O(N) + O(N) = O(2N) -> 简化为 O(N)。
 *         - 嵌套执行才是相乘关系：O(N) * O(N) = O(N^2)。
 * =============================================================================
 */

// ==================== 1. 核心算法实现 ====================

/**
 * @brief 打印 N x N 乘法网格矩阵
 * 
 * @param n 网格维度（输入规模 N）
 * 
 * @note 时间复杂度: O(N^2) —— 双层嵌套循环，基本打印操作执行 N * N 次
 * @note 空间复杂度: O(1)   —— 仅需 i, j 两个局部循环计数器
 */
void printMatrix(int n) {
    printf("=== 开始生成 %d x %d 乘法网格 ===\n", n, n);

    // 【外层循环】：控制行输出（共执行 N 轮）
    for (int i = 1; i <= n; i++) {
        // 【内层循环】：控制每行中的列输出（每轮外层均完整触发 N 次内层）
        for (int j = 1; j <= n; j++) {
            // 核心计算与输出操作：执行总频度为 N * N 次
            printf("%4d", i * j);
        }
        // 每一行输出完毕后换行
        printf("\n");
    }
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int n = 5;

    printf("==================== 平方阶时间复杂度 O(N^2) 测试 ====================\n");
    printf("输入规模 N = %d，理论基本操作频度 = %d^2 = %d 次\n\n", n, n, n * n);

    printMatrix(n);

    printf("\n复杂度总结: 时间 O(N^2) | 额外空间 O(1)\n");
    return 0;
}
