#include <stdio.h>

/**
 * 💡【知识点】时间复杂度 O(N^2) —— 平方阶时间复杂度
 * -----------------------------------------------------------------------------
 * 📌【核心思想与本质】
 *   1. 核心特征：双层嵌套循环。外层循环执行 N 次，每执行一次外层，内层循环都会完整执行 N 次。
 *      总操作次数约为 N * N = N^2（数据规模翻倍，计算量暴增 4 倍）。
 *   2. 常见场景：矩阵运算、冒泡排序、选择排序、网格图遍历。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法实现 ====================

/**
 * @brief 打印 N x N 乘法矩阵
 */
void printMatrix(int n) {
    // 外层循环：遍历行数 (共 N 行)
    for (int i = 1; i <= n; i++) {
        // 内层循环：遍历列数 (每行 N 列)
        for (int j = 1; j <= n; j++) {
            printf("%4d", i * j); // 🔍 执行总频度为 N * N 次
        }
        printf("\n");
    }
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int n = 5;
    printf("--- %d x %d 乘法矩阵 (时间复杂度 O(N^2)) ---\n", n, n);
    printMatrix(n);
    return 0;
}
