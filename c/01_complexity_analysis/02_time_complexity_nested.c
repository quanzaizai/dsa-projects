#include <stdio.h>

/**
 * 💡【知识点】时间复杂度 O(N^2) —— 平方阶时间复杂度
 * -----------------------------------------------------------------------------
 * 📌【概念与本质】
 *   当算法出现两层相互嵌套、且每层迭代次数均与输入规模 N 正相关的循环时，
 *   总操作次数为外层与内层循环次数的乘积（笛卡尔积模型）。
 *   若 N 翻倍，计算耗时会暴增 4 倍（2^2）；N 扩大 10 倍，耗时暴增 100 倍！
 * 
 * 📌【架构与模块分工】
 *   1. printMulTable() : 核心算法 —— 外层控制行、内层控制列，生成 N x N 二维网格。
 *   2. main()          : 驱动入口 —— 传入规模参数并触发打印。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 打印 n x n 乘法矩阵
 * 
 * 🔍【核心逻辑剖析】：
 *   • 嵌套循环的执行频度：
 *     - 外层循环 (Row)：控制表格的行数，i 从 1 遍历到 n，共执行 n 次。
 *     - 内层循环 (Col)：在每一行内，j 同样从 1 遍历到 n，每行执行 n 次。
 *     - 最内层语句 printf("%d\t", i * j)：总执行频度 = n (行) * n (列) = n^2 次。
 *   • 时空复杂度：
 *     - 时间复杂度: O(N^2)。常见于二维矩阵运算、基础排序（冒泡/选择/插入）。
 *     - 空间复杂度: O(1)，仅使用局部控制变量 i 和 j。
 */
void printMulTable(int n) {
    // 维度 1：行推进 (Row: 1 -> n)
    for (int i = 1; i <= n; i++) {
        
        // 维度 2：列推进 (Col: 1 -> n)，每次外层循环都会完整执行一整轮
        for (int j = 1; j <= n; j++) {
            printf("%d\t", i * j); // 核心计算与格式化输出 (总计 n^2 次)
        }
        
        printf("\n"); // 一行打印完毕后换行
    }
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int n = 5;
    printf("打印 %d x %d 乘法表 (总计算量: %d 次):\n", n, n, n * n);
    printMulTable(n);
    
    return 0;
}