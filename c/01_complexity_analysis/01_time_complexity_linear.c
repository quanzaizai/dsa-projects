#include <stdio.h>

/**
 * 💡【知识点】时间复杂度 O(N) —— 线性时间复杂度
 * -----------------------------------------------------------------------------
 * 📌【概念与本质】
 *   时间复杂度评估算法执行时间随输入规模 N 增长的趋势。
 *   O(N) 意味着操作次数与数据规模 N 成正比（如 N=1000 时，计算量大约是 N=100 时的 10 倍）。
 * 
 * 📌【架构与模块分工】
 *   1. sumArray() : 核心算法 —— 单层循环累加，实现 O(N) 线性遍历。
 *   2. main()     : 驱动入口 —— 负责数组初始化、长度计算与传参验证。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 计算整型数组所有元素的和
 * 
 * 🔍【核心逻辑剖析】：
 *   • 语句频度分析：
 *     - total 初始化：执行 1 次 -> O(1)
 *     - for 循环判断与累加：循环体依赖数组长度，严格执行 n 次 -> O(N)
 *     - return 语句：执行 1 次 -> O(1)
 *   • 总时间复杂度：T(n) = 1 + n + 1 = n + 2 -> 抓大放小，忽略常数项，记为 O(N)。
 *   • 空间复杂度：仅占用 total 和 i 两个变量，无额外内存开销 -> O(1)。
 */
int sumArray(int arr[], int n) {
    int total = 0; // 累加器初始化 (执行 1 次)
    
    // 单层循环：步长为 1，从 0 遍历至 n - 1，共执行 n 次
    for (int i = 0; i < n; i++) {
        total += arr[i]; // 核心操作：常数时间累加
    }
    
    return total;
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int nums[] = {10, 20, 30, 40, 50};
    
    /**
     * ⚠️【关键细节剖析：为什么必须在 main 中计算数组长度？】
     * 在 C 语言中，数组作为函数形参时会退化为指针（int*），丢失长度信息。
     * 此时若在 sumArray 中调用 sizeof(arr)，得到的是指针大小（64位系统为 8 字节）而非数组总字节！
     * 因此必须在定义数组的作用域内计算：总字节数 (20) / 单元素字节数 (4) = 5。
     */
    int size = sizeof(nums) / sizeof(nums[0]);
    
    int result = sumArray(nums, size);
    printf("数组元素总和: %d\n", result);

    return 0;
}