#include <stdio.h>

/**
 * =============================================================================
 * 💡【知识点】时间复杂度 (Time Complexity) —— 线性阶 O(N)
 * =============================================================================
 * 
 * 📌【1. 什么是大 O 渐进表示法 (Big-O Notation)？】
 *   大 O 符号用来衡量算法执行时间随输入规模 N 增长时的「增长趋势/数量级」，而非具体的微秒数。
 *   - 忽略常数项：例如 2N + 10 次基本操作，在大 O 记法下仍为 O(N)。
 *   - 忽略低阶项：例如 N^2 + 5N，当 N 极大时低阶项影响微乎其微，记为 O(N^2)。
 * 
 * 📌【2. 线性阶 O(N) 的本质与增长曲线】
 *   - 特征：算法的基本执行次数与输入规模 N 呈严格的「正比例关系」。
 *   - 对比示意图：
 * 
 *     耗时 ^
 *          |                                  /  O(N) 线性阶 (如单层循环)
 *          |                                 /
 *          |                                /
 *          |                               /
 *          |------------------------------/----  O(1) 常数阶 (如数组下标直达)
 *          +-----------------------------------> 数据规模 N
 * 
 * 📌【3. 深度思考与高频 Q&A】
 * 
 *   ❓ Q1: 循环里写了 `total += arr[i]` 和 `i++` 两条语句，为什么不是 O(2N)？
 *      👉 解答：大 O 记法关注的是规模扩大时的「增长斜率」。当 N 从 100 变成 1000（增长10倍），
 *         无论是 N 次操作还是 2N 次操作，耗时都增长了 10 倍。因此常数系数 2 被省略，统一抽象为 O(N)。
 * 
 *   ❓ Q2: 为什么 `sumArray` 函数内不能直接用 `sizeof(arr) / sizeof(arr[0])` 计算长度？
 *      👉 解答（C 语言经典大坑 —— 数组退化）：
 *         - 当数组名作为形参传递给函数时（如 `int arr[]` 或 `int *arr`），编译器会自动将其「退化为指针」。
 *         - 在 64 位系统下，`sizeof(arr)` 永远得到的是「指针本身的长度（8 字节）」，而不是原数组的总字节数！
 *         - 因此，数组的有效长度 N 必须在定义数组的作用域内计算好，并作为单独参数传递进函数。
 * =============================================================================
 */

// ==================== 1. 核心算法实现 ====================

/**
 * @brief 计算整型数组所有元素的累加和
 * 
 * @param arr 数组首地址（已退化为指针）
 * @param n   数组的有效元素个数
 * @return int 数组所有元素的总和
 * 
 * @note 时间复杂度: O(N) —— 循环体严格执行 N 次
 * @note 空间复杂度: O(1) —— 仅使用 total, i 两个整型局部变量，占用常数级内存
 */
int sumArray(const int arr[], int n) {
    // 【步骤 1】初始化累加器变量（常数时间 O(1)）
    int total = 0;

    // 【步骤 2】单层线性循环：从下标 0 遍历至 n-1
    // 循环条件检查、下标递增、数据累加总共执行 n 次基本操作 -> O(N)
    for (int i = 0; i < n; i++) {
        total += arr[i]; // 核心操作：通过基地址 + 偏移量直接取值累加
    }

    // 【步骤 3】返回计算结果
    return total;
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int nums[] = {10, 20, 30, 40, 50};

    // 💡【标准求数组长度公式】：总字节数 / 单个元素字节数
    int size = sizeof(nums) / sizeof(nums[0]);

    printf("==================== 线性时间复杂度 O(N) 测试 ====================\n");
    printf("输入数组规模 N = %d\n", size);
    
    int result = sumArray(nums, size);
    
    printf("计算所得累加和: %d\n", result);
    printf("算法复杂度结论: 时间 O(N) | 额外空间 O(1)\n");

    return 0;
}
