#include <stdio.h>

/**
 * 💡【知识点】时间复杂度 O(N) —— 线性时间复杂度
 * -----------------------------------------------------------------------------
 * 📌【核心思想与本质】
 *   1. 核心特征：算法执行时间随输入规模 N 呈线性同比例增长（如 N=1000 时耗时约为 N=100 时的 10 倍）。
 *   2. 时空复杂度：时间复杂度 O(N)（单层循环累加），额外变量占常数空间 -> 空间复杂度 O(1)。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 计算整型数组所有元素的和
 * @param arr 数组首地址
 * @param n   数组长度
 */
int sumArray(int arr[], int n) {
    int total = 0; // 累加器初始化

    // 🔍【单层遍历】：从 0 到 n-1 依次遍历累加，循环体严格执行 n 次 -> O(N)
    for (int i = 0; i < n; i++) {
        total += arr[i]; // 核心操作：常数时间累加
    }

    return total;
}

// ==================== 2. 测试与验证入口 ====================

int main(void) {
    int nums[] = {10, 20, 30, 40, 50};
    
    /**
     * ⚠️【关键细节：为什么必须在 main 中计算数组长度？】
     * 在 C 语言中，数组作为函数形参时会退化为指针（int*），丢失长度信息。
     * 此时若在 sumArray 中调用 sizeof(arr)，得到的是指针大小（64位系统为 8 字节）而非数组总大小！
     * 因此必须在定义数组的作用域内计算：总字节数 / 单个元素字节数。
     */
    int size = sizeof(nums) / sizeof(nums[0]);

    int result = sumArray(nums, size);
    printf("数组元素总和: %d\n", result);

    return 0;
}
