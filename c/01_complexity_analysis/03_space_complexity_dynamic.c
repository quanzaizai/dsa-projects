#include <stdio.h>
#include <stdlib.h>

/**
 * =============================================================================
 * 💡【知识点】空间复杂度 (Space Complexity) —— 线性阶 O(N) 与堆内存生命周期
 * =============================================================================
 * 
 * 📌【1. 什么是空间复杂度？】
 *   空间复杂度是指算法在运行过程中「额外开辟的辅助存储空间」随输入规模 N 变化的趋势。
 *   - 常见误区：代码本身的体积或输入数据本身的存储空间，通常不算作「辅助空间 (Auxiliary Space)」。
 *   - O(1) 辅助空间：仅开辟几个临时变量（如计数器 `int i`）。
 *   - O(N) 辅助空间：动态申请大小为 N 的数组、哈希表或深度为 N 的递归调用栈。
 * 
 * 📌【2. 内存分区模型图解 (Stack vs Heap)】
 * 
 *    内存低地址
 *   +----------------------------------------------------+
 *   | 代码段 (Text) & 全局数据段 (Data/BSS)              |
 *   +----------------------------------------------------+
 *   | 堆区 (Heap)  -> 向高地址增长                       |
 *   |  ▲                                                 |
 *   |  | [malloc(n * sizeof(int))] 动态开辟 N 个 int 空间 | <--- 产生 O(N) 空间开销！
 *   |  | (生命周期由程序员手动管理: malloc -> free)       |
 *   +----------------------------------------------------+
 *   |                         ... 未分配区 ...           |
 *   +----------------------------------------------------+
 *   | 栈区 (Stack) -> 向低地址增长                       |
 *   |  | 函数局部变量 (如 int n, int *my_arr)            | <--- 仅占常数级 O(1) 空间
 *   |  v (函数返回时由系统自动出栈回收)                  |
 *   +----------------------------------------------------+
 *    内存高地址
 * 
 * 📌【3. 深度思考与高频 Q&A】
 * 
 *   ❓ Q1: 为什么申请完堆内存后必须检查 `arr == NULL`？
 *      👉 解答：当物理内存耗尽或请求空间过大时，`malloc` 会失败并返回 `NULL`。
 *         如果不检查直接对 `arr[i]` 赋值，会导致致命的「空指针解引用 (Segmentation Fault)」导致程序直接崩溃。
 * 
 *   ❓ Q2: 为什么 `free(my_arr)` 之后还要加一句 `my_arr = NULL`？
 *      👉 解答（防御野指针）：
 *         - `free()` 只是将指针指向的那块堆内存归还给操作系统，并不会抹掉指针变量本身的值！
 *         - 此时 `my_arr` 仍然记录着那块已经被收回的旧地址（称为「野指针 / 悬挂指针 (Dangling Pointer)」）。
 *         - 显式赋 `NULL` 可以确保如果不小心再次使用该指针，能立刻被 `if (p != NULL)` 防御机制捕获。
 * =============================================================================
 */

// ==================== 1. 核心空间开辟逻辑 ====================

/**
 * @brief 在堆上动态创建长度为 n 的整型数组并完成初始化
 * 
 * @param n 需要开辟的数组元素数量（数据规模）
 * @return int* 指向堆内存连续空间首地址的指针；若分配失败则返回 NULL
 * 
 * @note 时间复杂度: O(N) —— 遍历完成 N 个元素的赋值初始化
 * @note 空间复杂度: O(N) —— 动态申请了 n * sizeof(int) 字节的堆空间
 */
int* createArray(int n) {
    // 【步骤 1】参数合法性校验
    if (n <= 0) {
        return NULL;
    }

    // 【步骤 2】向系统堆区申请 N 个整型连续空间 -> 引入 O(N) 空间开销
    int *arr = (int *)malloc((size_t)n * sizeof(int));

    // 【步骤 3】防崩溃检查：确认内存是否申请成功
    if (arr == NULL) {
        printf("⚠️ [内存分配失败] 无法为规模 N=%d 分配堆空间！\n", n);
        return NULL;
    }

    // 【步骤 4】填充初始数据
    for (int i = 0; i < n; i++) {
        arr[i] = (i + 1) * 10;
    }

    // 【步骤 5】将堆内存首地址返回给调用者（注意：此时堆内存依然驻留，未被释放）
    return arr;
}

// ==================== 2. 测试与内存释放闭环 ====================

int main(void) {
    int n = 5;

    printf("==================== 动态空间复杂度 O(N) 测试 ====================\n");
    printf("准备在堆区开辟 N = %d 个 int 的动态空间...\n", n);

    // 接收堆内存指针
    int *my_arr = createArray(n);

    // 使用堆内存数据
    if (my_arr != NULL) {
        printf("✅ 堆内存分配成功！数组内容为: ");
        for (int i = 0; i < n; i++) {
            printf("%d ", my_arr[i]);
        }
        printf("\n");

        // 【闭环释放 1】归还堆内存所有权
        free(my_arr);

        // 【闭环释放 2】将指针置空，彻底杜绝野指针 / 悬挂指针
        my_arr = NULL;
        printf("🧹 堆内存已安全 free 并将指针置 NULL\n");
    }

    return 0;
}
