#include <stdio.h>
#include <stdlib.h>

/**
 * 💡【知识点】空间复杂度 O(N) 与堆内存生命周期
 * -----------------------------------------------------------------------------
 * 📌【核心思想与本质】
 *   1. 核心特征：算法执行过程中额外开辟的内存空间与输入规模 N 呈线性正比（如 malloc 分配大小为 N 的动态数组）。
 *   2. 内存闭环：堆上分配的内存不受函数作用域限制，使用完毕必须显式调用 free 释放，防止内存泄漏。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心空间开辟逻辑 ====================

/**
 * @brief 动态创建长度为 n 的整型数组并初始化
 * @return 堆内存数组首地址
 */
int* createArray(int n) {
    // 🔍【空间开辟】：申请 n 个 int 空间 -> 空间复杂度 O(N)
    int *arr = (int *)malloc(n * sizeof(int));
    if (arr == NULL) {
        return NULL; // 防御性检查：内存分配失败
    }

    for (int i = 0; i < n; i++) {
        arr[i] = (i + 1) * 10;
    }
    return arr;
}

// ==================== 2. 测试与内存释放闭环 ====================

int main(void) {
    int n = 5;
    int *my_arr = createArray(n);

    if (my_arr != NULL) {
        printf("动态数组内容: ");
        for (int i = 0; i < n; i++) {
            printf("%d ", my_arr[i]);
        }
        printf("\n");

        // ⚠️【关键步骤】：手动释放堆内存并将指针置空
        free(my_arr);
        my_arr = NULL;
    }

    return 0;
}
