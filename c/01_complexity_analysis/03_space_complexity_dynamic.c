#include <stdio.h>
#include <stdlib.h> // 提供 malloc, free, NULL

/**
 * 💡【知识点】空间复杂度 O(N) 与 C 语言堆内存生命周期
 * -----------------------------------------------------------------------------
 * 📌【概念与本质】
 *   空间复杂度衡量算法在运行过程中为了完成任务所额外占用的内存空间。
 *   当新开辟的容器大小与输入规模 N 成正比时，空间复杂度为 O(N)。
 * 
 * 📌【底层次原理：栈内存 (Stack) vs 堆内存 (Heap)】
 *   • 栈内存：局部变量（如 int arr[5]）分配在栈上。函数一旦 return，栈帧被销毁，局部变量失效！
 *     若直接返回局部栈数组指针，会导致严重的“悬空指针 / 未定义行为”。
 *   • 堆内存：通过 malloc 显式申请的内存在堆区，其生命周期【跨越函数作用域】，直到手动 free。
 * 
 * 📌【架构与模块分工】
 *   1. squareArray() : 堆内存申请 -> 判空防御 -> 数据计算映射 -> 返回堆指针。
 *   2. main()        : 驱动入口 -> 获取指针 -> 遍历输出 -> 【必须 free】安全回收。
 * -----------------------------------------------------------------------------
 */

// ==================== 1. 核心算法逻辑 ====================

/**
 * @brief 将原数组元素计算平方，并在堆上开辟新数组保存返回
 * 
 * 🔍【核心逻辑剖析】：
 *   • 内存分配大小：n * sizeof(int)，确保根据平台整型长度精确分配所需字节数。
 *   • 防御性编程：若系统内存不足，malloc 会返回 NULL。必须进行判空检查，防止非法内存解引用。
 *   • 复杂度分析：
 *     - 时间复杂度: O(N)（需遍历 n 个元素计算平方）。
 *     - 空间复杂度: O(N)（额外申请了容纳 n 个整数的堆内存）。
 */
int* squareArray(int arr[], int n) {
    // 步骤 1：在堆区动态申请连续内存空间 (O(N) 空间开销)
    int* result = (int*)malloc(n * sizeof(int));
    
    // 步骤 2：防御性编程 —— 堆分配失败保护
    if (result == NULL) {
        printf("【系统错误】堆内存分配失败 (Out of Memory)！\n");
        return NULL;
    }

    // 步骤 3：数据映射 —— 遍历原数组写入平方值
    for (int i = 0; i < n; i++) {
        result[i] = arr[i] * arr[i];
    }
    
    // 步骤 4：返回堆内存指针（堆内存在函数返回后依然有效）
    return result; 
}

// ==================== 2. 测试与内存生命周期闭环 ====================

int main(void) {
    int nums[] = {1, 2, 3, 4, 5};
    int n = sizeof(nums) / sizeof(nums[0]);
    
    // 1. 调用算法，接收堆指针
    int* squared = squareArray(nums, n);

    // 2. 安全检查与打印验证
    if (squared != NULL) {
        printf("原数组:   ");
        for (int i = 0; i < n; i++) printf("%d ", nums[i]);
        printf("\n");

        printf("平方映射: ");
        for (int i = 0; i < n; i++) printf("%d ", squared[i]);
        printf("\n");
        
        /**
         * ⚠️【关键工程规范：堆内存闭环与防野指针】
         * ① free(squared) : 将堆内存还给操作系统，防止内存泄漏 (Memory Leak)。
         * ② squared = NULL : 释放后指针仍指向原地址（变为悬空指针），置 NULL 可防止误用野指针。
         */
        free(squared);
        squared = NULL;
    }
    
    return 0;
}
